from llama_index.core.prompts import PromptTemplate

EXTRACT_FILTERS_PROMPT = PromptTemplate(
    "Ты помогаешь искать резюме под конкретную вакансию.\n"
    "Ниже — до трёх текстов, написанных в свободной форме, каждый под "
    "своим заголовком. Какие-то из них могут отсутствовать.\n\n"
    "Что это за тексты:\n"
    "- ТРЕБОВАНИЯ ВАКАНСИИ — что нужно на этой конкретной позиции. "
    "Отсюда берётся предметная область, роль и технологии;\n"
    "- ОБЩИЕ ТРЕБОВАНИЯ — то, что компания спрашивает с любого "
    "кандидата: образование, языки, город, формат работы. Это редко "
    "говорит о профессии, поэтому в semantic_query, role_query и "
    "required_keywords отсюда не бери ничего;\n"
    "- ОТ РЕКРУТЁРА — что рекрутёр знает сверх текста вакансии, часто "
    "точнее её самой. Если он противоречит вакансии, прав он.\n\n"
    "Извлеки из них структурированные критерии поиска.\n\n"
    "Правила:\n"
    "- заполняй только то, что явно следует из текста; если критерия "
    "нет — оставь поле пустым, ничего не додумывай;\n"
    "- semantic_query — это НЕ список требований, а описание работы от "
    "первого лица кандидата: чем он занимался, с чем работал, какие "
    "задачи решал. Именно оно сопоставляется с описаниями опыта "
    "работы. Обязательно сохрани в нём лексику той отрасли и предметной "
    "области, о которых говорит вакансия: она отличает нужного "
    "кандидата от любого другого специалиста той же профессии;\n"
    "- role_query — одна короткая строка вида «должность, отрасль»: "
    "она сопоставляется с названиями должностей и компаний, где человек "
    "работал. Никаких инструментов и обязанностей, только позиция и "
    "предметная область;\n"
    "- must_keywords заполняй только из раздела ОТ РЕКРУТЁРА и только "
    "теми технологиями, инструментами или системами, которые он там "
    "назвал сам. Это самый весомый список: рекрутёр говорил с "
    "заказчиком и знает, ради чего вакансию открыли. Из вакансии и "
    "общих требований сюда не бери ничего. Если рекрутёр технологий не "
    "называл — оставь поле пустым. Разные написания одной технологии "
    "клади одной строкой через «|»: «ML|AI|ИИ»;\n"
    "- в professional_roles клади только ту роль, на которую реально "
    "ищут, одну или две. Не перечисляй смежные роли: каждая лишняя "
    "размывает поиск;\n"
    "- в optional_keywords собери все конкретные термины вакансии: "
    "технологии, протоколы, стандарты, методологии, типы документов, "
    "отрасль и предметную область, а также то, что названо желательным. "
    "Не клади общие слова вроде «опыт», «знание», «понимание». Ими "
    "кандидаты различаются между собой, но ни один из них никого не "
    "отсеивает;\n"
    "- required_keywords — два-три термина из текста вакансии, ради "
    "вакансию и открыли. Мысленно расставь собранные термины по "
    "редкости среди тех специалистов, которых ты нашёл бы по "
    "professional_roles: сверху то, что встретится в считаных резюме, "
    "снизу то, что есть почти у каждого из них. Бери сверху, отбрасывая "
    "то, без чего на эту работу всё-таки берут. Термин, который есть "
    "почти у каждого в профессии, не годится, каким бы обязательным его "
    "ни называла вакансия: он никого не выделяет. Смотри при этом на "
    "всю вакансию, а не на список обязательных требований: редкое чаще "
    "всего оказывается там, где написано «плюсом» или «понимание» — "
    "именно ради него вакансию и открыли, просто искать таких людей "
    "трудно. Если редкого нет вовсе — оставь поле пустым, это лучше, "
    "чем взять то, что есть у каждого. Не повторяй здесь "
    "professional_roles и role_query: должность и отрасль — не термины. "
    "Не повторяй здесь и must_keywords: то, что назвал рекрутёр, весит "
    "больше и уже посчитано. "
    "Кандидат, описавший такой термин в своём опыте, поднимется выше "
    "остальных, но никто из-за них не отсеивается. Клади только то, что "
    "кандидат пишет о себе сам: название технологии, продукта, "
    "стандарта или системы, ровно в том написании, в каком его пишет "
    "кандидат — без косых черт, скобок и пояснений. Термин — это имя, "
    "а не действие: одно-два слова, которыми вещь называется. Вышло "
    "словосочетание с отглагольным существительным — «проектирование "
    "чего-то», «описание чего-то», «понимание чего-то», «знание "
    "чего-то», «опыт чего-то» — значит, это переписанное требование, а "
    "не термин; оставь от него одно название самой вещи. Эти же "
    "термины "
    "оставь и в optional_keywords, дублирования здесь не бойся;\n"
    "- min_tenure_months заполняй, если просят человека, который "
    "задерживается на одном месте: «больше года на одном месте» — это "
    "12, «от двух лет» — 24. Речь именно о длительности одной работы, а "
    "не об общем стаже: общий стаж идёт в min_experience_years;\n"
    "- areas заполняй, только если назван конкретный город или регион. "
    "«Россия», «удалённо», «±2 часа от МСК» — это не регион, оставь "
    "поле пустым.\n\n"
    "Текст:\n{requirements}"
)
